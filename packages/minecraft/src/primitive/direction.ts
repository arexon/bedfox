/** A direction along one of the three axes. */
export type Direction = "north" | "east" | "south" | "west" | "up" | "down";

/** A direction along the vertical axis. */
export type VerticalDirection = "up" | "down";

/** A horizontal direction. */
export type CardinalDirection = "north" | "east" | "south" | "west";

/** A horizontal direction, or `random` for a random one. */
export type FacingDirection = "north" | "east" | "south" | "west" | "random";
